class NativeScalingTest(unittest.TestCase):
    def compare(self, mode):
        module = rolling if mode == "rolling" else expanding
        for (name, expected_mode, kind), bits in EXPECTED.items():
            if expected_mode != mode:
                continue
            with self.subTest(name=name, mode=mode, kind=kind):
                right, left = [np.array(values, dtype="<u8").view("<f8") for values in INPUTS[name]]
                before = [values.view("<u8").copy() for values in (right, left)]
                function = getattr(module, f"{mode}_{kind}")
                args = (left, right) if kind in ("corr", "cov") else (right,)
                actual = function(*args, *([3] if mode == "rolling" else []))
                missing = np.array([value is None for value in bits])
                np.testing.assert_array_equal(np.isnan(actual), missing)
                expected = np.array([value or 0 for value in bits], dtype="<u8")
                np.testing.assert_array_equal(actual.view("<u8")[~missing], expected[~missing])
                for values, untouched in zip((right, left), before):
                    np.testing.assert_array_equal(values.view("<u8"), untouched)

    @unittest.skipUnless(rolling.is_available(), "Native rolling library is unavailable")
    def test_rolling_preserves_v020_output_bits(self):
        self.compare("rolling")

    @unittest.skipUnless(expanding.is_available(), "Native expanding library is unavailable")
    def test_expanding_preserves_v020_output_bits(self):
        self.compare("expanding")


if __name__ == "__main__":
    unittest.main()
